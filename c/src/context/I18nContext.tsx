interface I18nContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: string, params?: Record<string, string | number>) => string
  tx: (zh: string, en: string) => string
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'zh',
  setLang: () => {},
  t: (key) => key,
  tx: (zh) => zh,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('yamibo-lang')
    return (saved === 'en' || saved === 'zh') ? saved : 'zh'
  })

  useEffect(() => {
    localStorage.setItem('yamibo-lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const setLang = (l: Lang) => setLangState(l)

  const t = (key: string, params?: Record<string, string | number>): string => {
    let value = TRANSLATIONS[lang][key] || TRANSLATIONS['zh'][key] || key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        value = value.replace(`{${k}}`, String(v))
      }
    }
    return value
  }

  const tx = (zh: string, en: string) => lang === 'en' ? en : zh

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tx }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
